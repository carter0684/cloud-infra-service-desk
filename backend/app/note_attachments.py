"""
Engineer Notes attachments — upload arbitrary photos/files to S3 and issue
short-lived presigned URLs for viewing/downloading them.

Why S3 (unlike profile photos, see profile_photo.py's docstring): Engineer
Notes need to support arbitrary file types (screenshots, logs, PDFs,
zips), potentially several per note, growing across a job's whole
lifetime. Inlining that as base64 directly on the DynamoDB job row (the
approach used for the single small profile-photo thumbnail) would risk
hitting DynamoDB's 400KB-per-item limit very quickly. This module is the
first place in the backend that talks to S3 — see
infra_cdk/stacks/data_stack.py's NoteAttachmentsBucket (private,
KMS-encrypted, BLOCK_ALL public access) and compute_stack.py's IAM grant
on the ECS task role.

The bucket itself is never exposed publicly: uploads go through this
backend (multipart POST -> boto3 put_object), and downloads/inline image
display are served via short-lived presigned GET URLs generated on
demand (see generate_presigned_get_url()), never a permanent public link.
"""

from __future__ import annotations

import os
import re
import uuid
from datetime import datetime, timezone
from typing import Optional

import boto3
from botocore.config import Config

AWS_REGION = os.environ.get("AWS_REGION", "us-east-1")
BUCKET_NAME = os.environ.get("NOTE_ATTACHMENTS_BUCKET_NAME", "")

# Per-file size cap. Generous enough for screenshots/photos/small logs
# while still bounding storage/cost — well above what DynamoDB inline
# base64 could ever support, which is the whole point of using S3 here.
MAX_ATTACHMENT_BYTES = 20 * 1024 * 1024  # 20 MB
MAX_ATTACHMENTS_PER_UPLOAD = 5

# How long a generated presigned GET URL stays valid. Short enough to
# limit exposure if a URL leaked (e.g. via browser history/logs), long
# enough that a slow page load or a large PDF download won't expire
# mid-transfer.
PRESIGNED_GET_EXPIRY_SECONDS = 300


class NoteAttachmentError(ValueError):
    """Raised for any invalid upload — message is safe to show the user."""


_s3_client = None


def _s3():
    global _s3_client
    if _s3_client is None:
        # IMPORTANT: force SigV4 explicitly. This bucket has SSE-KMS as
        # its *default* encryption (see infra_cdk/stacks/data_stack.py's
        # NoteAttachmentsBucket), and S3 requires SigV4 for any request
        # against an SSE-KMS object — that includes presigned GET URLs
        # generated by generate_presigned_get_url() below, not just the
        # put_object() upload call. Without this, some botocore/region
        # combinations (this bucket is in us-east-1, which still has a
        # legacy global endpoint) can fall back to signing with SigV2,
        # producing a presigned URL that S3 then rejects with:
        #   "Requests specifying Server Side Encryption with AWS KMS
        #    managed keys require AWS Signature Version 4."
        # That 403/XML error is exactly what a user sees if they open
        # the URL directly (the inline <img> and download link both use
        # this same presigned URL) — the upload itself still succeeds
        # because put_object doesn't go through the presigned-URL signer,
        # so this bug only shows up on view/download, not on upload.
        _s3_client = boto3.client(
            "s3",
            region_name=AWS_REGION,
            config=Config(signature_version="s3v4"),
        )
    return _s3_client


def _safe_filename(filename: str) -> str:
    """Strip path separators and any character that isn't safe in an S3
    key, so a malicious/odd filename can't traverse the key namespace or
    break URL encoding."""
    base = os.path.basename(filename or "file")
    cleaned = re.sub(r"[^A-Za-z0-9._-]", "_", base)
    return cleaned[:150] or "file"


def upload_attachment(
    *,
    job_id: str,
    note_id: str,
    filename: str,
    content_type: Optional[str],
    content: bytes,
    uploaded_by_email: str,
    uploaded_by_name: str,
) -> dict:
    """
    Validate and upload one attachment to S3, returning the metadata dict
    to append to the note's `attachments` list. Raises NoteAttachmentError
    for anything invalid.
    """
    if not BUCKET_NAME:
        raise NoteAttachmentError("Attachment storage is not configured on this server")
    if not content:
        raise NoteAttachmentError("Uploaded file is empty")
    if len(content) > MAX_ATTACHMENT_BYTES:
        raise NoteAttachmentError(
            f"'{filename}' is too large — maximum {MAX_ATTACHMENT_BYTES // (1024 * 1024)} MB per file"
        )

    content_type = content_type or "application/octet-stream"
    is_image = content_type.startswith("image/")
    attachment_id = str(uuid.uuid4())
    safe_name = _safe_filename(filename)
    s3_key = f"notes/{job_id}/{note_id}/{attachment_id}-{safe_name}"

    _s3().put_object(
        Bucket=BUCKET_NAME,
        Key=s3_key,
        Body=content,
        ContentType=content_type,
        ServerSideEncryption="aws:kms",
    )

    return {
        "id": attachment_id,
        "filename": filename or safe_name,
        "content_type": content_type,
        "is_image": is_image,
        "size_bytes": len(content),
        "s3_key": s3_key,
        "uploaded_by_email": uploaded_by_email,
        "uploaded_by": uploaded_by_name,
        "uploaded_at": datetime.now(timezone.utc).isoformat(),
    }


def generate_presigned_get_url(s3_key: str) -> str:
    """Short-lived presigned GET URL for viewing (inline <img>) or
    downloading (<a download>) one attachment. Generated fresh on every
    request — never cached/stored, since a stale URL would 403 once it
    expires."""
    if not BUCKET_NAME:
        raise NoteAttachmentError("Attachment storage is not configured on this server")
    return _s3().generate_presigned_url(
        "get_object",
        Params={"Bucket": BUCKET_NAME, "Key": s3_key},
        ExpiresIn=PRESIGNED_GET_EXPIRY_SECONDS,
    )


def delete_attachment(s3_key: str) -> None:
    """Best-effort delete of the underlying S3 object when an attachment
    (or its parent note) is removed. Never raises — a leftover orphaned
    object in a private bucket is a minor cost/cleanliness issue, not
    worth failing the user-facing delete operation over."""
    if not BUCKET_NAME:
        return
    try:
        _s3().delete_object(Bucket=BUCKET_NAME, Key=s3_key)
    except Exception:
        pass
